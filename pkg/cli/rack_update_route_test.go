package cli

import (
	"testing"

	"github.com/stretchr/testify/require"
)

func TestRackUpdateRoute(t *testing.T) {
	tests := []struct {
		current, target string
		route           []string
	}{
		{"3.24.9", "3.25.12", nil},
		{"3.24.9", "3.25.14", []string{"3.25.12", "3.25.14"}},
		{"3.24.9", "3.26.0", []string{"3.25.12", "3.25.14", "3.26.0"}},
		{"3.24.3", "3.25.12", nil},
		{"3.24.3", "3.25.14", []string{"3.24.11", "3.25.12", "3.25.14"}},
		{"3.24.5", "3.26.0", []string{"3.24.11", "3.25.12", "3.25.14", "3.26.0"}},
		{"3.24.6", "3.25.13", []string{"3.25.12", "3.25.13"}},
		{"3.24.2-noid-eh", "3.25.14", []string{"3.24.11", "3.25.12", "3.25.14"}},
		{"3.25.5", "3.25.14", nil},
		{"3.25.5", "3.26.0", []string{"3.25.14", "3.26.0"}},
		{"3.25.13", "3.26.1", []string{"3.25.14", "3.26.1"}},
		{"3.25.14", "3.26.1", nil},
		{"3.25.14rc2", "3.26.0", nil},
		{"3.25.12-arm64", "3.26.0", []string{"3.25.14", "3.26.0"}},
		{"3.24.11", "3.25.14rc1", []string{"3.25.12", "3.25.14rc1"}},
		{"3.23.3", "3.25.14", nil},
		{"3.23.3", "3.24.11", nil},
		{"3.26.0", "3.25.14", nil},
		{"3.24.9", "", nil},
		{"", "3.26.0", nil},
		{"dev1", "3.26.0", nil},
		{"21000101000000", "3.26.0", nil},
		{"3.24.9", "3.25", nil},
		{"4.24.9", "4.26.0", nil},
	}

	for _, tt := range tests {
		require.Equal(t, tt.route, rackUpdateRoute(tt.current, tt.target), "%s to %s", tt.current, tt.target)
	}
}
